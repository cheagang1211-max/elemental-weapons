package com.elementalweapons.boss;

/**
 * 재사용 보스 패턴 12종. 각 보스는 이 중 몇 개를 자기 속성/수치로 조합합니다.
 * 모든 공격은 피하기 전에 경고 표시(노란 원 → 빨간 원/선)가 먼저 나옵니다.
 */
public enum PatternType {
	/** 비: 플레이어 발밑에 경고 원 → 속성 착탄 (계속 움직여야 함) */
	RAIN(110),
	/** 돌진: 기를 모은 뒤 빨간 선 방향으로 돌진 */
	DASH(75),
	/** 고리: 보스 주변 원 → 폭발. 2페이즈부터 바깥 고리 추가 */
	NOVA(75),
	/** 표식: 모든 플레이어를 추적 → 위치 고정 → 거대 착탄 */
	MARK(95),
	/** 탄막: 보스가 속성 구체를 연속 발사 (약하게 유도) */
	BARRAGE(85),
	/** 내려찍기: 높이 솟았다가 땅을 내려찍어 퍼지는 충격파 (점프로 피함) */
	SLAM(70),
	/** 소용돌이: 플레이어를 보스 쪽으로 끌어당긴 뒤 폭발 */
	VORTEX(80),
	/** 소환: 부하 몹 소환 */
	SUMMON(40),
	/** 광선: 보스를 중심으로 회전하는 광선 (빈틈으로 피함) */
	BEAM(100),
	/** 궤도탄: 보스 주위를 돌며 나선형으로 퍼지는 구체들 */
	ORBIT(90),
	/** 운석: 큰 경고 원 → 하늘에서 거대한 구체 낙하 */
	METEOR(80),
	/** 순간이동: 플레이어 뒤로 순간이동 후 근거리 폭발 */
	BLINK(45);

	public final int duration;

	PatternType(int duration) {
		this.duration = duration;
	}
}
